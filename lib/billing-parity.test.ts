import { readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { periodBounds, subscriptionClock } from "./billing-periods";

// Parity between lib/billing-periods.ts (the reference) and the SQL mirror (private.local_day_start / private.cycle_period_bounds, migration 20261127000100): this test GENERATES the SQL check
// from the TypeScript functions and fails if supabase/tests/billing_parity.sql is not exactly what they produce today. The SQL file is then run in PostgreSQL by the CI, so a drift in either
// side is caught. To refresh the file after changing billing-periods.ts on purpose: UPDATE_PARITY=1 npx vitest run lib/billing-parity.test.ts
const FILE = "supabase/tests/billing_parity.sql";

const CASES: ReadonlyArray<{ anchor: string; tz: string; count: number }> = [
  { anchor: "2026-01-08", tz: "America/Costa_Rica", count: 14 },
  { anchor: "2026-01-29", tz: "America/Costa_Rica", count: 14 },
  { anchor: "2026-01-30", tz: "America/Costa_Rica", count: 14 },
  { anchor: "2026-01-31", tz: "America/Costa_Rica", count: 14 },
  { anchor: "2024-02-29", tz: "America/Costa_Rica", count: 26 }, // leap anchor: 28 Feb 2025, 29 Feb 2028 is outside the range
  { anchor: "2026-02-08", tz: "America/New_York", count: 14 }, // crosses both daylight-saving changes of 2026
  { anchor: "2026-03-08", tz: "America/New_York", count: 4 }, // the anchor day is the spring-forward day
  { anchor: "2026-01-31", tz: "Europe/London", count: 14 },
  { anchor: "2026-01-31", tz: "Asia/Kolkata", count: 6 }, // a half-hour offset
  { anchor: "2018-10-04", tz: "America/Sao_Paulo", count: 3 }, // 2018-11-04: midnight does not exist (the clock jumps 00:00 -> 01:00)
  // 2012-11-04: midnight happens twice. A HISTORICAL date on purpose: the offsets of a future date depend on the time-zone database version (in 2026 the ICU of Node, the PostgreSQL of the CI and an older local
  // PostgreSQL did not agree on Havana's December offset), and a parity check must not depend on that.
  { anchor: "2012-10-04", tz: "America/Havana", count: 3 },
  { anchor: "2011-11-30", tz: "Pacific/Apia", count: 3 }, // 2011-12-30 does not exist (the date line moved)
];

function build(): string {
  const rows: string[] = [];
  // One CONTROL per zone and year: the start of a plain local day (15 December) far from any transition. If the server's own time-zone data disagrees on it, the data is stale (not the date logic), and the
  // cases of that zone are skipped with a warning instead of reporting a false difference or passing silently.
  const controls = new Map<string, string>();
  for (const { anchor, tz } of CASES) {
    const key = `${tz}|${anchor.slice(0, 4)}-12-15`;
    if (!controls.has(key)) controls.set(key, periodBounds(subscriptionClock(key.split("|")[1] as string, tz), 0).startsAt);
  }
  const controlRows = [...controls].map(([key, startsAt]) => `    ('${key.split("|")[0]}', '${key.split("|")[1]}', '${startsAt}')`);
  for (const { anchor, tz, count } of CASES) {
    const clock = subscriptionClock(anchor, tz);
    for (let index = 0; index < count; index += 1) {
      const { startsAt, endsAt } = periodBounds(clock, index);
      rows.push(`    ('${anchor}', '${tz}', ${index}, '${startsAt}', '${endsAt}')`);
    }
  }
  return `-- GENERATED by lib/billing-parity.test.ts from lib/billing-periods.ts: do not edit by hand (refresh with UPDATE_PARITY=1 npx vitest run lib/billing-parity.test.ts).
-- Checks that the SQL date functions of the subscriptions migration give, for every case, the same instants as the TypeScript reference: the start of period N and its end, counted from the
-- original anchor, with the daylight-saving and date-line cases. Run with: psql -v ON_ERROR_STOP=1 -f supabase/tests/billing_parity.sql   (after every migration). Needs no data.
do $$
declare r record; bad text := ''; stale text := ''; compared int := 0; skipped int := 0;
  -- LOCAL ONLY: a developer machine whose PostgreSQL carries old time-zone data may set it (alter database ... set kynova.parity_allow_stale_tz = 'on'). The CI never sets it, so there EVERY case must be compared.
  allow_stale boolean := coalesce(current_setting('kynova.parity_allow_stale_tz', true), '') = 'on';
begin
  for r in select * from (values
${controlRows.join(",\n")}
  ) as c(tz, day, starts_at) loop
    if private.local_day_start(r.day::date, r.tz) is distinct from r.starts_at::timestamptz and position(r.tz in stale) = 0 then
      if not allow_stale then raise exception 'FAIL: the time-zone data of this server disagrees with the reference on a plain day (%): update the server data. Only a local machine may skip such zones, explicitly, with kynova.parity_allow_stale_tz = on', r.tz; end if;
      stale := stale || ' ' || r.tz;
    end if;
  end loop;
  if stale <> '' then raise warning 'LOCAL ONLY (kynova.parity_allow_stale_tz = on): the time-zone data of this server is old, cases skipped for:%', stale; end if;
  for r in select * from (values
${rows.join(",\n")}
  ) as v(anchor, tz, idx, starts_at, ends_at) loop
    if position(r.tz in stale) > 0 then skipped := skipped + 1; continue; end if;
    compared := compared + 1;
    if private.local_day_start((r.anchor::date + make_interval(months => r.idx))::date, r.tz) is distinct from r.starts_at::timestamptz
       or (select b.ends_at from private.cycle_period_bounds(r.anchor::date, r.tz, r.starts_at::timestamptz, r.idx) b) is distinct from r.ends_at::timestamptz then
      bad := bad || format(' %s %s #%s', r.anchor, r.tz, r.idx);
    end if;
  end loop;
  if bad <> '' then raise exception 'FAIL: the SQL period dates differ from the TypeScript reference for:%', bad; end if;
  if compared + skipped <> ${rows.length} or (stale = '' and compared <> ${rows.length}) then raise exception 'FAIL: % cases compared and % skipped of ${rows.length}', compared, skipped; end if;
  raise notice 'billing_parity: % of ${rows.length} cases compared and equal, % skipped (stale time-zone data:%)', compared, skipped, coalesce(nullif(stale, ''), ' none');
end $$;

select 'billing_parity: finished' as result;
`;
}

describe("the SQL period functions match the TypeScript reference", () => {
  it("supabase/tests/billing_parity.sql is exactly what billing-periods.ts produces (run in PostgreSQL by the CI)", () => {
    const expected = build();
    if (process.env.UPDATE_PARITY === "1") writeFileSync(FILE, expected);
    const actual = readFileSync(FILE, "utf8").replace(/\r\n/g, "\n");
    expect(actual).toBe(expected);
  });

  it("covers the awkward cases: a clamped 31st, a leap anchor, a midnight that does not exist, one that happens twice and a day that does not exist", () => {
    const sql = build();
    expect(sql).toContain("'2026-01-31', 'America/Costa_Rica', 1, '2026-02-28T06:00:00.000Z'");
    expect(sql).toContain("'2026-01-31', 'America/Costa_Rica', 2, '2026-03-31T06:00:00.000Z'"); // not chained: back to the 31st
    expect(sql).toContain("'2018-10-04', 'America/Sao_Paulo', 1, '2018-11-04T03:00:00.000Z'");
    expect(sql).toContain("'2012-10-04', 'America/Havana', 1, '2012-11-04T04:00:00.000Z'");
    expect(sql).toContain("'2011-11-30', 'Pacific/Apia', 1, '2011-12-30T10:00:00.000Z'");
  });
});
