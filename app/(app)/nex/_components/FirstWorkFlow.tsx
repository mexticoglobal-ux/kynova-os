"use client";

import { useMemo, useState } from "react";
import Link from "next/link";
import { ArrowLeft, CheckCircle2, FileText, Info } from "lucide-react";
import { usePipeline } from "@/components/pipeline/PipelineProvider";
import { useSession } from "@/components/session/SessionProvider";
import { Badge } from "@/components/ui/Badge";
import { buttonClass } from "@/components/ui/Button";
import { apiFetch } from "@/lib/api/client";
import { ROLE_LABEL } from "@/lib/contracts/backend";
import { isDraftResult, type FirstWorkDraftResult } from "@/lib/contracts/first-work-draft";
import { FIRST_WORK_AI } from "@/lib/first-work-draft";
import { EXECUTION_NOTE, HISTORY_TITLE, NEEDS, NEED_LABEL, buildDeliverable, effectiveNeed, planText, priorityFor, recommend, type Need } from "@/lib/first-work";

const FIELD = "field min-h-11 w-full text-base";

// What the server answered, kept with the phrases it was asked about: it only applies while the person's phrases are still those.
type ServerState =
  | { phase: "idle" }
  | { phase: "loading" }
  | { phase: "done"; offer: string; audience: string; result: FirstWorkDraftResult }
  | { phase: "error"; kind: "forbidden" | "unauthorized" | "invalid" | "unavailable" };
const RULES_ON_SCREEN = "Se muestra el borrador por reglas de su pantalla.";

// First useful work: one question at most, one priority with its reason, one draft ready to review. The logic is `lib/first-work.ts`; this draws it and
// keeps apart what is real data, what was generated by rules and what is the simulated chat, and three states: example, saved draft, executed action.
export function FirstWorkFlow({ onExit, onDeepen, onSave, saveFailed }: { onExit: () => void; onDeepen: () => void; onSave: (text: string, title: string) => void; saveFailed: boolean }) {
  const session = useSession();
  const { sorted, canWrite } = usePipeline();
  const [offer, setOffer] = useState("");
  const [audience, setAudience] = useState("");
  const ctx = useMemo(
    () => ({ demo: session.mode === "demo", companyName: session.mode === "backend" ? session.tenantName : null, roleLabel: ROLE_LABEL[session.role], canWrite, leads: sorted, offer, audience }),
    [session, canWrite, sorted, offer, audience],
  );
  const suggested = useMemo(() => recommend(ctx), [ctx]);
  const [need, setNeed] = useState<Need | null>(null);
  const [saved, setSaved] = useState(false);
  const chosen = need ?? suggested.need;
  const advice = useMemo(() => priorityFor(chosen, ctx), [chosen, ctx]);
  const deliverable = useMemo(() => buildDeliverable(chosen, ctx), [chosen, ctx]);
  const askContext = effectiveNeed(chosen, ctx) === "clients";
  const [server, setServer] = useState<ServerState>({ phase: "idle" });
  // the server's draft applies only to the phrases it was asked about; if they changed, the rules draft of the screen is shown again
  const current = server.phase === "done" && server.offer === offer && server.audience === audience ? server.result : null;
  const shown = useMemo(
    () => current && askContext && deliverable.kind === "clients"
      ? { ...deliverable, pieces: [{ label: deliverable.pieces[0]?.label ?? "Mensaje propuesto", text: current.draft.message }, { label: deliverable.pieces[1]?.label ?? "Pieza de presentación (borrador)", text: current.draft.presentation }], needsContext: current.needsContext }
      : deliverable,
    [current, askContext, deliverable],
  );
  const origin = current && shown !== deliverable ? current.label : session.mode === "demo" ? "Reglas de KYNOVA en su pantalla (modo demostración)." : "Reglas de KYNOVA en su pantalla; no se consultó al servidor.";
  const role = ROLE_LABEL[session.role];
  // What went wrong is said as what it is: a refused permission is not a provider failure, and a failure to reach the server is not either.
  const notice =
    server.phase === "error"
      ? server.kind === "forbidden" ? `Su rol (${role}) no permite pedir este borrador al servidor. ${RULES_ON_SCREEN}`
        : server.kind === "unauthorized" ? `Su sesión terminó: inicie sesión de nuevo. ${RULES_ON_SCREEN}`
        : server.kind === "invalid" ? `Revise las frases (hasta 160 caracteres cada una). ${RULES_ON_SCREEN}`
        : `No se pudo consultar el servidor. ${RULES_ON_SCREEN}`
      : server.phase === "done" && !current ? `Cambió el texto: pulse «Redactar con NEX» para actualizar. Mientras tanto, ${RULES_ON_SCREEN.toLowerCase()}`
      : null;

  async function askServer() {
    if (session.mode !== "backend") return;
    const snapshot = { offer, audience };
    setServer({ phase: "loading" });
    setSaved(false);
    const response = await apiFetch<unknown>("/api/v1/nex/draft", { body: { tenantId: session.tenantId, ...snapshot } });
    if (response.ok && isDraftResult(response.data)) setServer({ phase: "done", ...snapshot, result: response.data });
    else setServer({ phase: "error", kind: !response.ok && response.status === 403 ? "forbidden" : !response.ok && response.status === 401 ? "unauthorized" : !response.ok && response.status === 400 ? "invalid" : "unavailable" });
  }
  const prospects = sorted.length;

  return (
    <div className="mx-auto max-w-2xl space-y-5">
      <button type="button" onClick={onExit} className="inline-flex items-center gap-1 text-sm text-ink-muted hover:text-ink">
        <ArrowLeft aria-hidden className="h-4 w-4" /> Volver
      </button>

      <header className="space-y-1">
        <h2 className="text-2xl font-semibold">Su primera prioridad</h2>
        <p className="text-sm text-ink-muted">
          {session.mode === "backend" ? `${session.tenantName} · su rol: ${ROLE_LABEL[session.role]}` : "Modo demostración · datos de ejemplo"}
          {` · Prospectos en el Pipeline: ${prospects}`}
        </p>
      </header>

      <section aria-labelledby="fw-need" className="space-y-2">
        <h3 id="fw-need" className="text-sm font-medium">¿Qué necesita ahora?</h3>
        <div className="flex flex-wrap gap-2">
          {NEEDS.map((item) => (
            <button key={item} type="button" aria-pressed={chosen === item} onClick={() => { setNeed(item); setSaved(false); }} className={buttonClass(chosen === item ? "primary" : "secondary", "md")}>
              {NEED_LABEL[item]}
              {item === suggested.need && need === null ? " · recomendado" : ""}
            </button>
          ))}
        </div>
      </section>

      {askContext ? (
        <section aria-labelledby="fw-context" className="space-y-3 rounded-xl border border-line p-4">
          <h3 id="fw-context" className="text-sm font-medium">Dos frases para que el borrador sea suyo (opcional)</h3>
          <div className="space-y-1">
            <label htmlFor="fw-offer" className="text-sm text-ink-soft">¿Qué ofrece su empresa?</label>
            <input id="fw-offer" value={offer} maxLength={160} onChange={(event) => { setOffer(event.target.value); setSaved(false); }} placeholder="Ej.: campañas de marketing para pequeños negocios" className={FIELD} />
          </div>
          <div className="space-y-1">
            <label htmlFor="fw-audience" className="text-sm text-ink-soft">¿A quién se dirige?</label>
            <input id="fw-audience" value={audience} maxLength={160} onChange={(event) => { setAudience(event.target.value); setSaved(false); }} placeholder="Ej.: restaurantes y cafés" className={FIELD} />
          </div>
          <p className="text-xs text-ink-muted">Si lo deja vacío, el borrador marca [completar: …] y no inventa nada.</p>
          {session.mode === "backend" ? (
            <div className="space-y-1">
              <button type="button" onClick={() => void askServer()} disabled={server.phase === "loading" || !canWrite} className={buttonClass("secondary", "md")}>
                {server.phase === "loading" ? "Consultando…" : "Redactar con NEX"}
              </button>
              {!canWrite ? <p className="text-xs text-ink-muted">Su rol ({role}) no permite pedir este borrador al servidor; abajo se muestra el borrador por reglas de su pantalla.</p> : null}
            </div>
          ) : null}
        </section>
      ) : null}

      <section aria-labelledby="fw-priority" className="card space-y-1 p-4">
        <h3 id="fw-priority" className="text-xs font-medium uppercase tracking-wide text-ink-muted">Prioridad</h3>
        <p className="font-medium">{advice.priority}</p>
        <p className="text-sm text-ink-soft">{advice.why}</p>
      </section>

      <section aria-labelledby="fw-draft" className="card space-y-3 p-4">
        <div className="flex flex-wrap items-center justify-between gap-2">
          <h3 id="fw-draft" className="flex items-center gap-2 font-medium">
            <FileText aria-hidden className="h-4 w-4 text-primary" /> {shown.title}
          </h3>
          {saved ? <Badge tone="success">Borrador guardado</Badge> : <Badge tone="warning">{shown.basis === "example" ? "Ejemplo" : "Borrador sin guardar"}</Badge>}
        </div>
        {shown.items.length > 0 ? (
          <ul className="space-y-2 text-sm">
            {shown.items.map((item, index) => (
              <li key={`${item.label}-${index}`} className="flex gap-3">
                <span className="w-28 shrink-0 text-ink-muted">{item.label}</span>
                <span>
                  {item.task}
                  {item.note ? <span className="block text-xs text-ink-muted">{item.note}</span> : null}
                </span>
              </li>
            ))}
          </ul>
        ) : null}
        {shown.pieces.map((piece) => (
          <figure key={piece.label} className="rounded-xl border border-line bg-shade p-3 text-sm">
            <figcaption className="mb-1 text-xs text-ink-muted">{piece.label} · no enviado</figcaption>
            <p className="whitespace-pre-line">{piece.text}</p>
          </figure>
        ))}
        {shown.needsContext.length > 0 ? <p className="text-xs text-ink-muted">Falta completar: {shown.needsContext.join("; ")}.</p> : null}
        {askContext ? <p className="text-xs text-ink-muted">Origen del texto: {origin}</p> : null}
        {notice ? <p role="status" className="text-xs text-warning">{notice}</p> : null}
      </section>

      <section aria-labelledby="fw-origin" className="space-y-2 rounded-xl border border-line p-4 text-sm">
        <h3 id="fw-origin" className="flex items-center gap-2 font-medium"><Info aria-hidden className="h-4 w-4" /> De dónde sale esto</h3>
        <ul className="list-disc space-y-1 pl-5 text-ink-soft">
          <li><strong>Datos consultados:</strong> {session.mode === "backend" ? `su empresa (${session.tenantName}), su rol y ${prospects} ${prospects === 1 ? "prospecto" : "prospectos"} del Pipeline.` : "ninguno real: es la demostración con datos de ejemplo."}</li>
          <li><strong>Contenido:</strong> {FIRST_WORK_AI.enabled ? "lo indica la línea «Origen del texto»: reglas de KYNOVA o, si el servidor lo usó, un modelo de IA." : "generado por reglas de KYNOVA; el modelo de IA está desactivado."}</li>
          <li><strong>Chat libre de NEX:</strong> sigue siendo simulado; esto no es una respuesta de ese chat.</li>
        </ul>
      </section>

      <section aria-labelledby="fw-state" className="space-y-2 rounded-xl border border-line p-4 text-sm">
        <h3 id="fw-state" className="font-medium">Estado</h3>
        <p><strong>Acciones ejecutadas:</strong> ninguna.</p>
        <p>
          <strong>{saved ? "Borrador guardado" : "Borrador"}:</strong>{" "}
          {saved ? (session.mode === "backend" ? "quedó en su historial de NEX, privado para usted." : "quedó en el historial de este navegador (demostración).") : "todavía no se ha guardado."}
        </p>
        <p className="text-ink-soft">{EXECUTION_NOTE}</p>
        {saveFailed ? <p role="alert" className="text-danger">No se pudo guardar el borrador. Inténtelo de nuevo.</p> : null}
      </section>

      <div className="flex flex-wrap gap-2">
        <button type="button" disabled={saved} onClick={() => { onSave(planText(shown, advice, askContext ? origin : undefined), HISTORY_TITLE[shown.kind]); setSaved(true); }} className={buttonClass("primary", "md")}>
          {saved ? <><CheckCircle2 aria-hidden className="h-4 w-4" /> Guardado</> : "Guardar borrador"}
        </button>
        <button type="button" onClick={onDeepen} className={buttonClass("secondary", "md")}>Profundizar: diagnóstico completo (opcional)</button>
        <Link href="/sales" className={buttonClass("secondary", "md")}>Ir a Ventas</Link>
      </div>
      <p className="text-xs text-ink-muted">La captación de visitantes es otro recorrido (NEX › chat de captación): allí sí se pide un medio de contacto. Esta pantalla es su trabajo como usuario de la empresa.</p>
    </div>
  );
}
